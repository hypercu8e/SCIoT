"""Render checked binary artifacts as C arrays; never recalibrate a model."""

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
DEFAULT = HERE.parent / "activation_compression" / "esp32_prep_2026-10-19"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def array(name, data):
    lines = [f"alignas(16) static const uint8_t {name}[] = {{"]
    for offset in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{x:02x}" for x in data[offset:offset + 20]) + ",")
    return "\n".join([*lines, "};"])


def generate(source, target):
    manifest = json.loads((source / "manifest.json").read_text())
    if not manifest["verification"]["split_matches_full_output_byte_for_byte"]:
        raise ValueError("Split verification did not pass")
    raw = (source / "vectors.npz").read_bytes()
    if digest(raw) != manifest["vectors_sha256"]:
        raise ValueError("Test vectors hash mismatch")
    with np.load(source / "vectors.npz", allow_pickle=False) as vectors:
        selected = vectors["frame_indices"].tolist()
        if selected != manifest["selected_frame_indices"]:
            raise ValueError("Unexpected frame indices")
        lines = ["// Generated by generate_assets.py. Do not edit.", "#pragma once", "#include <stdint.h>"]
        lines.append("static const int kFrameIndices[] = {" + ", ".join(map(str, selected)) + "};")
        lines.append(f"static const int kCases = {len(selected)};")
        stages = [("full", "inputs", "outputs"), ("prefix", "inputs", "boundaries"),
                  ("suffix", "boundaries", "outputs")]
        for stage_id, (stage, input_key, output_key) in enumerate(stages):
            binary = (source / f"{stage}.tflite").read_bytes()
            description = manifest["models"][stage]
            if digest(binary) != description["sha256"]:
                raise ValueError(f"Model hash mismatch: {stage}")
            lines += [f"#if MODEL_STAGE == {stage_id}",
                      f'static const char kStage[] = "{stage}";',
                      f'static const char kModelSha256[] = "{description["sha256"]}";',
                      f'static const char kVectorsSha256[] = "{manifest["vectors_sha256"]}";',
                      array("kModel", binary)]
            for role, key in (("Input", input_key), ("Output", output_key)):
                values = vectors[key]
                spec = description[role.lower()]
                if values.dtype != np.int8 or list(values.shape[1:]) != spec["shape"][1:]:
                    raise ValueError(f"Wrong {stage} {role} vector type/shape")
                lines += [f"static const int k{role}Bytes = {values[0].nbytes};",
                          f"static const float k{role}Scale = {spec['scales'][0]:.17g}f;",
                          f"static const int k{role}Zero = {spec['zero_points'][0]};",
                          "static const int k" + role + "Shape[] = {" + ", ".join(map(str, spec["shape"])) + "};"]
                for i, item in enumerate(values):
                    lines.append(array(f"k{role}{i}", item.tobytes()))
                lines.append(f"static const uint8_t* const k{role}Cases[] = {{" +
                             ", ".join(f"k{role}{i}" for i in range(len(values))) + "};")
            lines.append("#endif")
        lines += ['#if MODEL_STAGE < 0 || MODEL_STAGE > 2', '#error "Unknown MODEL_STAGE"', '#endif']
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("\n".join(lines) + "\n")
    print(f"Generated {target} ({target.stat().st_size} bytes)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--artifacts", type=Path, default=DEFAULT)
    parser.add_argument("--output", type=Path, default=HERE / "include/generated/assets.h")
    args = parser.parse_args()
    generate(args.artifacts, args.output)

